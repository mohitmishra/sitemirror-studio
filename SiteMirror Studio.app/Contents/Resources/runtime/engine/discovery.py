def _norm(url: str, base: str) -> Optional[str]:
    if not url:
        return None
    try:
        u = urljoin(base, url.strip())
        p = urlparse(u)
        if p.scheme not in {"http", "https"}:
            return None
        return p._replace(fragment="").geturl()
    except Exception:
        return None


def _rootish(host: str) -> str:
    h = host.lower().split(":")[0]
    return h[4:] if h.startswith("www.") else h


def _same_site(url: str, root_host: str) -> bool:
    try:
        return _rootish(urlparse(url).netloc) == _rootish(root_host)
    except Exception:
        return False


def _localname(tag: Any) -> str:
    if not isinstance(tag, str):
        return ""
    return tag.split("}", 1)[-1].lower()


def _isoish(value: Optional[str]) -> bool:
    if not value:
        return False
    v = value.strip()
    # Sitemap lastmod accepts W3C datetime/date. Keep validation permissive but useful.
    if re.match(r"^\d{4}-\d{2}-\d{2}([Tt ].*)?$", v):
        return True
    try:
        parsedate_to_datetime(v)
        return True
    except Exception:
        return False




def _edge_block_info(status: Optional[int], text: str, headers: Optional[Dict[str, str]] = None) -> Dict[str, Any]:
    low = (text or "").lower()[:30000]
    hdr = {str(k).lower(): str(v).lower() for k, v in (headers or {}).items()}
    provider = None
    if (
        "generated by cloudfront" in low
        or "the request could not be satisfied" in low
        or "request blocked. we can't connect to the server for this app or website" in low
        or "x-amz-cf-id" in hdr
        or "cloudfront" in hdr.get("server", "")
        or "cloudfront" in hdr.get("via", "")
    ):
        provider = "CloudFront"
    elif "akamai" in low or "akamai" in hdr.get("server", ""):
        provider = "Akamai"
    elif "fastly" in low or "fastly" in hdr.get("server", "") or "x-served-by" in hdr:
        provider = "Fastly"
    elif "incapsula" in low or "imperva" in low or "incap_ses" in hdr.get("set-cookie", ""):
        provider = "Imperva"
    blocked = bool(provider and status in {401, 403, 429, 503})
    return {"blocked": blocked, "provider": provider}

def _looks_challenge(status: Optional[int], text: str) -> Tuple[bool, Optional[str]]:
    low = (text or "").lower()[:12000]
    markers = [
        "performing security verification",
        "this website uses a security service to protect against malicious bots",
        "verify you are human",
        "checking your browser",
        "just a moment",
        "attention required",
        "cf-chl-",
        "/cdn-cgi/challenge-platform/",
        "challenge-platform",
        "cloudflare ray id",
        "performance & security by cloudflare",
        "performance and security by cloudflare",
        "captcha",
        "access denied",
        "security check",
    ]
    if status in {401, 403, 429}:
        return True, "HTTP %s from direct crawler" % status
    for marker in markers:
        if marker in low:
            return True, "Protection/challenge page detected"
    return False, None


@dataclass
class FetchResult:
    url: str
    final_url: str
    status: Optional[int]
    content_type: str
    body: bytes
    text: str
    headers: Dict[str, str]
    error: Optional[str] = None


class DirectDiscovery:
    """Discover site structure without opening a browser.

    Order of operations:
    robots.txt -> declared sitemaps -> homepage hints -> common sitemap endpoints
    -> nested sitemap indexes -> HTML sitemap pages -> feeds.
    """

    def __init__(self, start_url: str, session: requests.Session, should_stop: Optional[Callable[[], bool]] = None):
        self.start_url = start_url if "://" in start_url else "https://" + start_url
        self.root_host = urlparse(self.start_url).netloc
        self.session = session
        self.should_stop = should_stop or (lambda: False)
        self.urls: Set[str] = set()
        self.sitemap_urls: Set[str] = set()
        self.lastmod: Dict[str, str] = {}
        self.feed_published: Dict[str, str] = {}
        self.report: Dict[str, Any] = {
            "strategy": "discovery-first",
            "direct_http": True,
            "browser_used": False,
            "visible_browser_used": False,
            "browser_reason": None,
            "robots": {},
            "homepage": {},
            "sitemaps": [],
            "html_sitemaps": [],
            "feeds": [],
            "standards": [],
            "urls_discovered": 0,
        }
        self._sitemap_seen: Set[str] = set()
        self._candidate_seen: Set[str] = set()

    def fetch(self, url: str, timeout: int = 12) -> FetchResult:
        if self.should_stop():
            raise RuntimeError("SiteMirror crawl stopped by user")
        result = {}
        done = threading.Event()

        def worker():
            try:
                result["response"] = self.session.get(url, timeout=timeout, allow_redirects=True, headers={"Accept": "*/*"})
            except Exception as exc:
                result["error"] = exc
            finally:
                done.set()

        threading.Thread(target=worker, daemon=True, name="SiteMirrorDiscoveryFetch").start()
        while not done.wait(0.10):
            if self.should_stop():
                raise RuntimeError("SiteMirror crawl stopped by user")
        if self.should_stop():
            raise RuntimeError("SiteMirror crawl stopped by user")
        try:
            if "error" in result:
                raise result["error"]
            r = result["response"]
            ctype = (r.headers.get("content-type") or "").split(";", 1)[0].strip().lower()
            enc = r.encoding or "utf-8"
            try:
                text = r.content.decode(enc, errors="replace")
            except Exception:
                text = r.text
            return FetchResult(
                url=url,
                final_url=r.url,
                status=r.status_code,
                content_type=ctype,
                body=r.content,
                text=text,
                headers=dict(r.headers),
            )
        except Exception as exc:
            return FetchResult(url=url, final_url=url, status=None, content_type="", body=b"", text="", headers={}, error=str(exc))

    def inspect_robots(self) -> List[str]:
        robots_url = urljoin(self.start_url, "/robots.txt")
        fr = self.fetch(robots_url)
        out: Dict[str, Any] = {
            "url": robots_url,
            "status": fr.status,
            "present": fr.status == 200,
            "content_type": fr.content_type,
            "sitemaps": [],
            "allow_rules": 0,
            "disallow_rules": 0,
            "issues": [],
        }
        declared: List[str] = []
        if fr.status == 200:
            for line in fr.text.splitlines():
                stripped = line.strip()
                if not stripped or stripped.startswith("#"):
                    continue
                if ":" not in stripped:
                    continue
                key, value = stripped.split(":", 1)
                key = key.strip().lower()
                value = value.strip()
                if key == "sitemap" and value:
                    absolute = _norm(value, robots_url)
                    if absolute:
                        declared.append(absolute)
                        out["sitemaps"].append(absolute)
                        if not re.match(r"^https?://", value, re.I):
                            out["issues"].append("Sitemap directive should use an absolute URL")
                elif key == "allow":
                    out["allow_rules"] += 1
                elif key == "disallow":
                    out["disallow_rules"] += 1
            out["valid"] = True
            if not out["sitemaps"]:
                out["notes"] = ["No Sitemap directive. This is optional, but declaring sitemap locations helps crawlers discover them."]
        elif fr.status in {404, 410}:
            out["valid"] = True
            out["notes"] = ["robots.txt is not present. That is allowed; there are no robots.txt rules to apply."]
        elif fr.status in {401, 403}:
            out["valid"] = False
            out["issues"].append("robots.txt is blocked to crawlers")
        elif fr.status is None:
            out["valid"] = False
            out["issues"].append(fr.error or "robots.txt could not be fetched")
        elif fr.status and fr.status >= 500:
            out["valid"] = False
            out["issues"].append("robots.txt returned a server error")
        else:
            out["valid"] = True
        self.report["robots"] = out
        return list(dict.fromkeys(declared))

    def inspect_homepage(self) -> Tuple[List[str], List[str], List[str], bool, Optional[str]]:
        fr = self.fetch(self.start_url, timeout=18)
        challenge, reason = _looks_challenge(fr.status, fr.text)
        edge = _edge_block_info(fr.status, fr.text, fr.headers)
        explicit_human = bool(challenge and not edge.get("blocked") and any(marker in (fr.text or "").lower()[:12000] for marker in (
            "performing security verification", "this website uses a security service to protect against malicious bots",
            "verify you are human", "checking your browser", "just a moment", "cf-chl-",
            "/cdn-cgi/challenge-platform/", "challenge-platform", "cloudflare ray id", "captcha"
        )))
        home = {
            "url": self.start_url,
            "final_url": fr.final_url,
            "status": fr.status,
            "content_type": fr.content_type,
            "reachable": bool(fr.status and fr.status < 500),
            "challenge": challenge,
            "explicit_human_challenge": explicit_human,
            "edge_block": bool(edge.get("blocked")),
            "edge_provider": edge.get("provider"),
            "issues": [],
        }
        if fr.error:
            home["issues"].append(fr.error)
        if fr.status and fr.status >= 400:
            home["issues"].append("HTTP %s" % fr.status)
        self.report["homepage"] = home

        sitemap_hints: List[str] = []
        html_hints: List[str] = []
        feed_hints: List[str] = []
        if fr.status and fr.status < 400 and "html" in fr.content_type:
            soup = BeautifulSoup(fr.text, "html.parser")
            for link in soup.find_all("link", href=True):
                rels = " ".join(link.get("rel") or []).lower()
                typ = (link.get("type") or "").lower()
                href = _norm(link.get("href"), fr.final_url)
                if not href:
                    continue
                if "sitemap" in rels:
                    sitemap_hints.append(href)
                if "alternate" in rels and ("rss" in typ or "atom" in typ or "xml" in typ):
                    feed_hints.append(href)
            for a in soup.find_all("a", href=True):
                href = _norm(a.get("href"), fr.final_url)
                if not href:
                    continue
                hay = ((a.get_text(" ", strip=True) or "") + " " + (a.get("href") or "")).lower()
                if "sitemap" in hay or "site map" in hay or "site-map" in hay:
                    if href.lower().endswith((".xml", ".xml.gz", ".txt")):
                        sitemap_hints.append(href)
                    else:
                        html_hints.append(href)
        return (
            list(dict.fromkeys(sitemap_hints)),
            list(dict.fromkeys(html_hints)),
            list(dict.fromkeys(feed_hints)),
            challenge,
            reason,
        )

    def _parse_xml_sitemap(self, fr: FetchResult, source: str) -> Dict[str, Any]:
        item: Dict[str, Any] = {
            "url": fr.url,
            "final_url": fr.final_url,
            "source": source,
            "status": fr.status,
            "kind": "unknown",
            "valid": False,
            "url_count": 0,
            "child_sitemaps": 0,
            "lastmod_count": 0,
            "issues": [],
            "notes": [],
        }
        raw = fr.body
        if fr.url.lower().endswith(".gz") or fr.content_type in {"application/gzip", "application/x-gzip"}:
            try:
                raw = gzip.decompress(raw)
            except Exception as exc:
                item["issues"].append("Gzip decompression failed: %s" % exc)
                return item
        if len(raw) > MAX_SITEMAP_BYTES:
            item["issues"].append("Sitemap exceeds 50 MB uncompressed protocol limit")
        parser = etree.XMLParser(resolve_entities=False, no_network=True, recover=False, huge_tree=False)
        try:
            root = etree.fromstring(raw, parser=parser)
        except Exception as exc:
            item["issues"].append("Invalid XML: %s" % str(exc).split("\n", 1)[0])
            return item

        name = _localname(root.tag)
        ns_uri = ""
        if isinstance(root.tag, str) and root.tag.startswith("{"):
            ns_uri = root.tag[1:].split("}", 1)[0]
        if name not in {"urlset", "sitemapindex"}:
            item["issues"].append("XML root is not urlset or sitemapindex")
            return item
        item["kind"] = name
        item["valid"] = True
        if ns_uri != SITEMAP_NS:
            item["notes"].append("Sitemap namespace is missing or differs from the Sitemap Protocol 0.9 namespace")

        entries = []
        for child in list(root):
            if _localname(child.tag) not in {"url", "sitemap"}:
                continue
            loc = None
            lastmod = None
            for field in list(child):
                lname = _localname(field.tag)
                if lname == "loc":
                    loc = (field.text or "").strip()
                elif lname == "lastmod":
                    lastmod = (field.text or "").strip()
            if loc:
                entries.append((loc, lastmod))

        if len(entries) > MAX_SITEMAP_URLS:
            item["issues"].append("Contains more than 50,000 entries")
        for loc, lastmod in entries:
            if not re.match(r"^https?://", loc, re.I):
                item["issues"].append("Contains non-absolute <loc> URL")
                continue
            if lastmod:
                item["lastmod_count"] += 1
                if not _isoish(lastmod):
                    item["notes"].append("One or more <lastmod> values are not recognizable W3C-style dates")
            if name == "sitemapindex":
                item["child_sitemaps"] += 1
                self._enqueue_sitemap(loc, "sitemap-index")
            else:
                item["url_count"] += 1
                if _same_site(loc, self.root_host):
                    self.urls.add(loc)
                    self.sitemap_urls.add(loc)
                    if lastmod:
                        self.lastmod[loc] = lastmod
        item["issues"] = list(dict.fromkeys(item["issues"]))
        item["notes"] = list(dict.fromkeys(item["notes"]))
        return item

    def _parse_text_sitemap(self, fr: FetchResult, source: str) -> Dict[str, Any]:
        lines = [x.strip() for x in fr.text.splitlines() if x.strip() and not x.strip().startswith("#")]
        urls = [x for x in lines if re.match(r"^https?://", x, re.I)]
        valid = bool(urls) and len(urls) == len(lines)
        item = {
            "url": fr.url,
            "final_url": fr.final_url,
            "source": source,
            "status": fr.status,
            "kind": "text",
            "valid": valid,
            "url_count": len(urls),
            "child_sitemaps": 0,
            "lastmod_count": 0,
            "issues": [] if valid else ["Text sitemap contains lines that are not absolute URLs"],
            "notes": [],
        }
        if len(urls) > MAX_SITEMAP_URLS:
            item["issues"].append("Contains more than 50,000 URLs")
        for u in urls:
            if _same_site(u, self.root_host):
                self.urls.add(u)
                self.sitemap_urls.add(u)
        return item

    def _inspect_sitemap_url(self, url: str, source: str) -> Optional[Dict[str, Any]]:
        if url in self._sitemap_seen:
            return None
        self._sitemap_seen.add(url)
        fr = self.fetch(url, timeout=18)
        if fr.status is None or fr.status >= 400:
            # Common-path probes that don't exist are not errors; declared/indexed ones are.
            if source in {"robots.txt", "homepage", "sitemap-index"}:
                return {
                    "url": url,
                    "final_url": fr.final_url,
                    "source": source,
                    "status": fr.status,
                    "kind": "unavailable",
                    "valid": False,
                    "url_count": 0,
                    "child_sitemaps": 0,
                    "lastmod_count": 0,
                    "issues": [fr.error or ("HTTP %s" % fr.status)],
                    "notes": [],
                }
            return None
        ctype = fr.content_type
        low = fr.text[:500].lower()
        if "xml" in ctype or fr.url.lower().endswith((".xml", ".xml.gz")) or low.lstrip().startswith("<?xml") or "<urlset" in low or "<sitemapindex" in low:
            return self._parse_xml_sitemap(fr, source)
        if ctype.startswith("text/plain") or fr.url.lower().endswith(".txt"):
            return self._parse_text_sitemap(fr, source)
        # A 200 HTML page at a guessed .xml path is usually a soft-404/homepage rewrite.
        return None

    def _enqueue_sitemap(self, url: str, source: str) -> None:
        if not hasattr(self, "_sitemap_queue"):
            self._sitemap_queue = deque()
        normalized = _norm(url, self.start_url)
        if normalized and normalized not in self._candidate_seen:
            self._candidate_seen.add(normalized)
            self._sitemap_queue.append((normalized, source))

    def inspect_html_sitemap(self, url: str, source: str) -> Optional[Dict[str, Any]]:
        fr = self.fetch(url, timeout=12)
        if not fr.status or fr.status >= 400 or "html" not in fr.content_type:
            return None
        soup = BeautifulSoup(fr.text, "html.parser")
        internal = []
        for a in soup.find_all("a", href=True):
            u = _norm(a.get("href"), fr.final_url)
            if u and _same_site(u, self.root_host):
                internal.append(u)
        internal = list(dict.fromkeys(internal))
        # Avoid treating a generic navigation page/homepage soft-404 as an HTML sitemap.
        text = (soup.get_text(" ", strip=True) or "").lower()
        looks_named = "sitemap" in text[:5000] or "site map" in text[:5000] or "sitemap" in url.lower() or "site-map" in url.lower()
        if not looks_named or len(internal) < 3:
            return None
        for u in internal:
            self.urls.add(u)
        return {
            "url": url,
            "final_url": fr.final_url,
            "source": source,
            "status": fr.status,
            "kind": "html",
            "valid": True,
            "url_count": len(internal),
            "issues": [],
            "notes": ["HTML sitemap discovered. HTML sitemaps help users/navigation but are separate from XML Sitemap Protocol files."],
        }

    def inspect_feed(self, url: str, source: str) -> Optional[Dict[str, Any]]:
        fr = self.fetch(url, timeout=10)
        if not fr.status or fr.status >= 400:
            return None
        low = fr.text[:1000].lower()
        if not ("<rss" in low or "<feed" in low or "application/rss" in fr.content_type or "application/atom" in fr.content_type):
            return None
        urls: List[str] = []
        try:
            soup = BeautifulSoup(fr.text, "xml")
            # RSS items: <link>URL</link> + <pubDate>.
            for item_node in soup.find_all("item"):
                link_node = item_node.find("link")
                href = link_node.get_text(strip=True) if link_node else None
                u = _norm(href, fr.final_url) if href else None
                if u and _same_site(u, self.root_host):
                    urls.append(u)
                    date_node = item_node.find("pubDate") or item_node.find("dc:date")
                    if date_node and date_node.get_text(strip=True):
                        self.feed_published[u] = date_node.get_text(strip=True)
            # Atom entries: <link href=...> + <published>/<updated>.
            for entry in soup.find_all("entry"):
                link_node = entry.find("link", href=True) or entry.find("link")
                href = (link_node.get("href") if link_node and link_node.has_attr("href") else (link_node.get_text(strip=True) if link_node else None))
                u = _norm(href, fr.final_url) if href else None
                if u and _same_site(u, self.root_host):
                    urls.append(u)
                    date_node = entry.find("published") or entry.find("updated")
                    if date_node and date_node.get_text(strip=True):
                        self.feed_published[u] = date_node.get_text(strip=True)
            # Generic links not nested in item/entry.
            for link in soup.find_all("link"):
                href = link.get("href") or link.get_text(strip=True)
                u = _norm(href, fr.final_url) if href else None
                if u and _same_site(u, self.root_host):
                    urls.append(u)
        except Exception:
            pass
        urls = list(dict.fromkeys(urls))
        for u in urls:
            self.urls.add(u)
        return {"url": url, "source": source, "status": fr.status, "kind": "feed", "url_count": len(urls), "valid": True}

    def run(self) -> Dict[str, Any]:
        if self.should_stop():
            raise RuntimeError("SiteMirror crawl stopped by user")
        declared = self.inspect_robots()
        home_xml, home_html, home_feeds, challenge, reason = self.inspect_homepage()

        self._sitemap_queue = deque()
        for u in declared:
            self._enqueue_sitemap(u, "robots.txt")
        for u in home_xml:
            self._enqueue_sitemap(u, "homepage")

        # If the homepage is already returning an edge/WAF denial or an explicit browser
        # challenge, do not spray dozens of guessed sitemap/feed endpoints from the same
        # direct HTTP client. That can make the CDN more suspicious and can poison the
        # subsequent real-browser retry. Inspect only explicitly declared/hinted locations
        # and let the browser session perform the rest of discovery after access succeeds.
        limited_direct = bool(self.report.get("homepage", {}).get("edge_block") or self.report.get("homepage", {}).get("challenge"))
        if not limited_direct:
            for path in COMMON_SITEMAP_PATHS:
                self._enqueue_sitemap(urljoin(self.start_url, path), "common-location")

        while self._sitemap_queue and len(self._sitemap_seen) < 250:
            if self.should_stop():
                raise RuntimeError("SiteMirror crawl stopped by user")
            u, source = self._sitemap_queue.popleft()
            item = self._inspect_sitemap_url(u, source)
            if item:
                self.report["sitemaps"].append(item)

        html_candidates = list(dict.fromkeys(home_html + ([] if limited_direct else [urljoin(self.start_url, p) for p in HTML_SITEMAP_PATHS])))
        for u in html_candidates[:30]:
            if self.should_stop():
                raise RuntimeError("SiteMirror crawl stopped by user")
            item = self.inspect_html_sitemap(u, "homepage" if u in home_html else "common-location")
            if item:
                self.report["html_sitemaps"].append(item)

        feed_candidates = list(dict.fromkeys(home_feeds + ([] if limited_direct else [urljoin(self.start_url, p) for p in FEED_PATHS])))
        for u in feed_candidates[:20]:
            if self.should_stop():
                raise RuntimeError("SiteMirror crawl stopped by user")
            item = self.inspect_feed(u, "homepage" if u in home_feeds else "common-location")
            if item:
                self.report["feeds"].append(item)

        self.urls.add(self.start_url)
        self.report["urls_discovered"] = len(self.urls)
        self.report["direct_access_limited"] = limited_direct
        if self.report.get("homepage", {}).get("edge_block"):
            provider = self.report.get("homepage", {}).get("edge_provider") or "CDN/WAF"
            self.report["browser_reason"] = "%s blocked direct discovery; switching to one dedicated browser session" % provider
        else:
            self.report["browser_reason"] = reason if challenge else None

        valid_xml = [x for x in self.report["sitemaps"] if x.get("valid")]
        declared_valid = [x for x in valid_xml if x.get("source") == "robots.txt"]
        self.report["standards"] = [
            {
                "name": "robots.txt at site root",
                "status": "good" if self.report["robots"].get("valid") else "issue",
                "detail": "Present" if self.report["robots"].get("present") else "Not present",
            },
            {
                "name": "Sitemap discovery",
                "status": "good" if valid_xml else "warning",
                "detail": "%s valid sitemap file(s) found" % len(valid_xml) if valid_xml else "No valid XML/text sitemap found",
            },
            {
                "name": "Sitemap declared in robots.txt",
                "status": "good" if declared_valid else "info",
                "detail": "%s valid declared sitemap(s)" % len(declared_valid) if declared_valid else "Not declared; optional but recommended for discovery",
            },
            {
                "name": "Nested sitemap indexes",
                "status": "good",
                "detail": "%s sitemap file(s) inspected recursively" % len(self.report["sitemaps"]),
            },
        ]
        return self.report
